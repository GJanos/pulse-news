const { withAppBuildGradle } = require('@expo/config-plugins');

// Stock Expo prebuild signs the release build with the public Android debug key.
// A sideloaded APK's signature can never change in place, so shipping v1 that way
// would force every user to uninstall (and lose their data) once a real key is used.
//
// This plugin adds a `release` signing config fed by environment variables and points
// the release build type at it. Without the variables the release config has no
// storeFile, so Gradle fails the release build loudly instead of silently falling back
// to the debug key. Debug builds are unaffected.
//
//   PULSE_UPLOAD_STORE_FILE      absolute path to the .keystore
//   PULSE_UPLOAD_STORE_PASSWORD
//   PULSE_UPLOAD_KEY_ALIAS
//   PULSE_UPLOAD_KEY_PASSWORD
//
// android/ is generated by prebuild, so this lives in a config plugin rather than a
// hand-edited build.gradle.
const MARKER = '// pulse:release-signing';

const RELEASE_SIGNING_CONFIG = `
        release { ${MARKER}
            if (System.getenv('PULSE_UPLOAD_STORE_FILE')) {
                storeFile file(System.getenv('PULSE_UPLOAD_STORE_FILE'))
                storePassword System.getenv('PULSE_UPLOAD_STORE_PASSWORD')
                keyAlias System.getenv('PULSE_UPLOAD_KEY_ALIAS')
                keyPassword System.getenv('PULSE_UPLOAD_KEY_PASSWORD')
            }
        }`;

/** Pure build.gradle transform — exported for unit testing. Idempotent. */
function applyReleaseSigning(gradle) {
  if (gradle.includes(MARKER)) return gradle;

  const signingDebug = /(signingConfigs\s*\{\s*debug\s*\{[^}]*\})/;
  if (!signingDebug.test(gradle)) {
    throw new Error('withReleaseSigning: signingConfigs.debug block not found in build.gradle');
  }
  const withConfig = gradle.replace(signingDebug, `$1${RELEASE_SIGNING_CONFIG}`);

  const releaseUsesDebug =
    /(buildTypes\s*\{[\s\S]*?release\s*\{[\s\S]*?)signingConfig signingConfigs\.debug/;
  if (!releaseUsesDebug.test(withConfig)) {
    throw new Error(
      'withReleaseSigning: release buildType signingConfig not found in build.gradle',
    );
  }
  return withConfig.replace(releaseUsesDebug, '$1signingConfig signingConfigs.release');
}

const withReleaseSigning = (config) =>
  withAppBuildGradle(config, (config) => {
    config.modResults.contents = applyReleaseSigning(config.modResults.contents);
    return config;
  });

module.exports = withReleaseSigning;
module.exports.applyReleaseSigning = applyReleaseSigning;
